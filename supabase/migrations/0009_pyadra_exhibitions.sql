-- Purpose: one row per "exhibition of one", the small museum room
--   the house makes for one person (src/app/house/). While the house
--   makes each room by hand, rows are written by hand in the Table
--   Editor, the way pyadra_settings is edited. No page writes here.
--
--   A room is private. It is never written into the repository
--   (which is public) and it is found only by its slug, so the slug
--   must not be guessable: a word and a random tail,
--   e.g. 'elena-x7k2p9q4'. The slug 'la-doctora' is the sample room
--   and lives in code, not here.
--
-- pieces: a JSON list. Each item is one of
--   { "kind": "song",     "title": "...", "note": "...", "src": "https://...", "duration": "2:43" }
--   { "kind": "letter",   "from": "...",  "opensAt": "YYYY-MM-DD", "body": "..." }
--   { "kind": "figurine", "image": "https://...", "caption": "..." }
--   The server withholds a letter's body until opensAt (house/exhibition.ts
--   -> seal). It is stored as plain text: private, not unreadable by the
--   operator, and the Privacy page says so.
--
-- RLS on, no public policies: read server-side with the service role
--   key through src/app/house/store.ts, like every other table.
-- ============================================================

CREATE TABLE public.pyadra_exhibitions (
  slug TEXT PRIMARY KEY CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(slug) BETWEEN 12 AND 80),
  for_name TEXT NOT NULL,
  dedication TEXT,
  from_name TEXT,
  opened_on DATE NOT NULL DEFAULT CURRENT_DATE,
  -- the admission number printed on the ticket
  number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  -- the carrier's code, when the room arrived through one
  carried_by TEXT,
  pieces JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(pieces) = 'array'),
  -- who commissioned it: for the house's own records, never shown in the room
  giver_email TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TRIGGER trg_pyadra_exhibitions_updated_at
  BEFORE UPDATE ON public.pyadra_exhibitions
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

ALTER TABLE public.pyadra_exhibitions ENABLE ROW LEVEL SECURITY;
